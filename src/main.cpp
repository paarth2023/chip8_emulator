#include "opengl_renderer.h"

#include <cstdint>
#include <fstream>
#include <ios>
#include <iostream>
#include "chip8.h"
#include "keyboard.h"

#define u8 uint8_t
#define u16 uint16_t

u8 font[] = {
	0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
	0x20, 0x60, 0x20, 0x20, 0x70, // 1
	0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
	0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
	0x90, 0x90, 0xF0, 0x10, 0x10, // 4
	0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
	0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
	0xF0, 0x10, 0x20, 0x40, 0x40, // 7
	0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
	0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
	0xF0, 0x90, 0xF0, 0x90, 0x90, // A
	0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
	0xF0, 0x80, 0x80, 0x80, 0xF0, // C
	0xE0, 0x90, 0x90, 0x90, 0xE0, // D
	0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
	0xF0, 0x80, 0xF0, 0x80, 0x80  // F
};


int main() {
	OpenGLRenderer renderer(64, 32, 640, 320, "chip-8 emulator");

	if (!renderer.initialize())
		return -1;

	Chip8 emulator{};
	keyboard* input = new keyboard();
	std::cout << "Callback was set\n";
	renderer.setKeyCallback(input->keyCallback);
	std::cout << "After the callback\n";

	emulator.setFont(font);
	emulator.loadRom("IBM Logo.ch8");
	emulator.init();

	while (!renderer.shouldClose()) {
		// Fetch
		emulator.fetch();
		emulator.decode();

		//opengl render part
		renderer.render(emulator.display);
		renderer.pollEvents();
	}

	return 0;
}